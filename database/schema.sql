-- Initial CHWOO database and table definitions.
-- Import before seed_products.sql.

CREATE DATABASE IF NOT EXISTS chwoo_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE chwoo_db;

-- 1. Product catalogue: one row per product (not per purchase)
CREATE TABLE IF NOT EXISTS products (
    product_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    product_name VARCHAR(120) NOT NULL,
    category VARCHAR(30) NOT NULL,
    price DECIMAL(8, 2) NOT NULL,
    image_path VARCHAR(255) NOT NULL,
    description TEXT,
    stock_quantity INT UNSIGNED NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (product_id)
) ENGINE=InnoDB;

-- 2. Customers: password_hash holds a hash generated by PHP password_hash(),
--    never a plaintext password.
CREATE TABLE IF NOT EXISTS customers (
    customer_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(190) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (customer_id),
    UNIQUE KEY uq_customers_email (email)
) ENGINE=InnoDB;

-- 3. Orders: one row per checkout, belonging to one customer.
--    Payment is simulated for this course project; no payment card data stored.
CREATE TABLE IF NOT EXISTS orders (
    order_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    customer_id INT UNSIGNED NOT NULL,
    order_status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    payment_status VARCHAR(30) NOT NULL DEFAULT 'Pending',
    delivery_address TEXT NOT NULL,
    total_amount DECIMAL(10, 2) NOT NULL,
    ordered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (order_id),
    KEY idx_orders_customer (customer_id),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
) ENGINE=InnoDB;

-- 4. Order items: each row is a line item in a customer's order.
--    We copy unit_price into order_items to preserve the original purchase price.
CREATE TABLE IF NOT EXISTS order_items (
    order_item_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id INT UNSIGNED NOT NULL,
    product_id INT UNSIGNED NOT NULL,
    quantity INT UNSIGNED NOT NULL,
    selected_size VARCHAR(10) NOT NULL,
    selected_colour VARCHAR(50) NOT NULL,
    unit_price DECIMAL(8, 2) NOT NULL,
    PRIMARY KEY (order_item_id),
    KEY idx_order_items_order (order_id),
    KEY idx_order_items_product (product_id),
    CONSTRAINT fk_items_order FOREIGN KEY (order_id)
        REFERENCES orders (order_id),
    CONSTRAINT fk_items_product FOREIGN KEY (product_id)
        REFERENCES products (product_id)
) ENGINE=InnoDB;
